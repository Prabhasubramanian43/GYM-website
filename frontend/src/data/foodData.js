// Automatically load all food images from the assets folder.
const imageFiles = import.meta.glob("../assets/**/*.{jpeg,jpg,png,webp}", {
  eager: true,
  import: "default",
});

// Find an image by its filename.
// If the image is not found, use homeImage as a fallback.
const getImage = (filename) => {
  const imagePath = Object.keys(imageFiles).find((path) =>
    path.toLowerCase().endsWith(`/${filename.toLowerCase()}`),
  );

  return imagePath ? imageFiles[imagePath] : homeImage;
};

